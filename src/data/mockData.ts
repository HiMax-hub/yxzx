/**
 * 从产品库自动派生默认银行准入配置（按 银行×产品类别 聚合）
 * 保证管理后台「银行产品准入配置」覆盖全部产品类别，与产品库/匹配引擎保持一致
 */
export function buildDefaultBankPolicies(): BankProductPolicy[] {
  const groups = new Map<string, MatchedProduct[]>();
  for (const p of INITIAL_PRODUCTS) {
    if (!p.bankName || !p.category) continue;
    const key = `${p.bankName}||${p.category}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key)!.push(p);
  }
  const policies: BankProductPolicy[] = [];
  for (const [key, prods] of groups) {
    const [bankName, category] = key.split('||');
    const maxAmount = Math.max(...prods.map((p) => p.maxAmount));
    const baseRateRange = prods[0].interestRateRange || '以银行当期报价为准';
    const admissionRule = prods[0].requirements.slice(0, 3).join('；');
    policies.push({ bankName, category, baseRateRange, maxAmount, admissionRule, status: 'active' });
  }
  return policies.sort((a, b) => a.bankName.localeCompare(b.bankName, 'zh') || a.category.localeCompare(b.category, 'zh'));
}

